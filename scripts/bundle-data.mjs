import fs from "fs";
import path from "path";

const DATA_ROOT = path.join(process.cwd(), "src/data");
const OUTPUT_FILE = path.join(DATA_ROOT, "bundled.ts");

function readJsonRecursive(dir, baseDir = "") {
  const results = {};
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    const relativePath = path.join(baseDir, entry.name);
    if (entry.isDirectory()) {
      Object.assign(results, readJsonRecursive(fullPath, relativePath));
    } else if (entry.name.endsWith(".json")) {
      const key = relativePath.replace(/\.json$/, "").replace(/[\/\-]/g, "_");
      results[key] = JSON.parse(fs.readFileSync(fullPath, "utf-8"));
    }
  }
  return results;
}

console.log("📦 Bundling data files...");
const allData = readJsonRecursive(DATA_ROOT);
const keys = Object.keys(allData).sort();

let output = `// Auto-generated by scripts/bundle-data.mjs — DO NOT EDIT
// This file bundles all static data for Cloudflare Workers compatibility
// Generated at: ${new Date().toISOString()}
// @ts-nocheck

`;

for (const key of keys) {
  const varName = `_${key.replace(/[^a-zA-Z0-9_]/g, "_")}`;
  const jsonStr = JSON.stringify(allData[key]).replace(/\n/g, "");
  output += `export const ${varName} = ${jsonStr} as const;\n\n`;
}

output += `export const BUNDLED_DATA = {\n`;
for (const key of keys) {
  const varName = `_${key.replace(/[^a-zA-Z0-9_]/g, "_")}`;
  output += `  "${key}": ${varName},\n`;
}
output += `} as const;\n`;

fs.writeFileSync(OUTPUT_FILE, output, "utf-8");
console.log(`✅ Bundled ${keys.length} data files → ${OUTPUT_FILE}`);
console.log(`📄 Generated ${output.length.toLocaleString()} characters`);
